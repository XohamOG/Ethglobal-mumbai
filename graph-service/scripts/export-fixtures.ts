import * as fs from "fs";
import * as path from "path";
import { GraphIngestionEngine } from "../src/ingestion.js";

async function run() {
  const engine = new GraphIngestionEngine();
  console.log("Generating fresh fixtures for frontend and CRE integration...");
  const rebuild = await engine.rebuildGraph({
    protocolId: "aave-v3-mainnet",
    triggeredBy: "manual",
  });

  const fixturesDir = path.resolve(process.cwd(), "../docs/fixtures");
  if (!fs.existsSync(fixturesDir)) {
    fs.mkdirSync(fixturesDir, { recursive: true });
  }

  // 1. mock-graph.json
  const mockGraphPath = path.join(fixturesDir, "mock-graph.json");
  fs.writeFileSync(mockGraphPath, JSON.stringify(rebuild, null, 2), "utf-8");
  console.log(`[+] Wrote ${mockGraphPath}`);

  // 2. sample-rebuild-response.json
  const sampleResponse = {
    success: true,
    snapshotId: rebuild.snapshotId,
    protocolId: rebuild.protocolId,
    compositeScore: rebuild.compositeScore,
    riskTier: rebuild.riskTier,
    evaluatedAtBlock: rebuild.evaluatedAtBlock,
    fingerprint: rebuild.fingerprint,
    swarmGraphRef: rebuild.swarmGraphRef,
    swarmEvidenceRef: rebuild.swarmEvidenceRef,
    nodeCount: rebuild.nodeCount,
    hopScores: rebuild.hopScores,
  };
  const responsePath = path.join(fixturesDir, "sample-rebuild-response.json");
  fs.writeFileSync(responsePath, JSON.stringify(sampleResponse, null, 2), "utf-8");
  console.log(`[+] Wrote ${responsePath}`);

  // 3. graph-data.ts for frontend drop-in
  const protocolsData = [
    {
      protocolId: "aave-v3-mainnet",
      name: "Aave V3",
      category: "Lending Protocol",
      chain: "Ethereum Mainnet",
      compositeScore: rebuild.compositeScore,
      riskTier: rebuild.riskTier,
      lastEvaluatedBlock: rebuild.evaluatedAtBlock,
      coreNodesCount: rebuild.nodes.filter((n) => n.hop === 0).length,
      directDepsCount: rebuild.nodes.filter((n) => n.hop === 1).length,
      transitiveDepsCount: rebuild.nodes.filter((n) => n.hop === 2).length,
      fingerprint: rebuild.fingerprint,
    },
  ];

  const graphDataTsContent = `/**
 * DeFi Provenance Graph - Shared Protocol & Graph Fixtures
 * Generated by graph-service (vedaXD) for Next.js Frontend (XohamOG)
 */

export interface GraphNode {
  id: string;
  label: string;
  address: string;
  hop: number;
  category: "proxy" | "implementation" | "oracle" | "multisig" | "token" | string;
  riskScore: number;
  proxyType: "eip1967" | "beacon" | "eip897" | "none";
  adminType: "timelock" | "safe" | "eoa" | "dao" | "none";
  sourcifyStatus: "full_match" | "partial_match" | "not_found";
  referencedProtocolId?: string;
  safeOwnerCount?: number;
  safeThreshold?: number;
  safeOwners?: string[];
  oracleStaleness?: number;
}

export interface GraphEdge {
  from: string;
  to: string;
  label: string;
  type: string;
}

export const PROTOCOLS = ${JSON.stringify(protocolsData, null, 2)};

export const AAVE_NODES: GraphNode[] = ${JSON.stringify(
    rebuild.nodes.map((n) => ({
      id: n.id,
      label: n.label,
      address: n.address,
      hop: n.hop,
      category: n.category,
      riskScore: n.riskScore,
      proxyType: n.proxyType,
      adminType: n.adminType,
      sourcifyStatus: n.sourcifyStatus,
      referencedProtocolId: n.referencedProtocolId || undefined,
      safeOwnerCount: n.safeOwnerCount || undefined,
      safeThreshold: n.safeThreshold || undefined,
      safeOwners: n.safeOwners && n.safeOwners.length > 0 ? n.safeOwners : undefined,
      oracleStaleness: n.oracleStaleness,
    })),
    null,
    2
  )};

export const AAVE_EDGES: GraphEdge[] = ${JSON.stringify(rebuild.edges, null, 2)};
`;

  const graphDataTsPath = path.join(fixturesDir, "graph-data.ts");
  fs.writeFileSync(graphDataTsPath, graphDataTsContent, "utf-8");
  console.log(`[+] Wrote ${graphDataTsPath}`);
}

run().catch(console.error);

